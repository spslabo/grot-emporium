#!/usr/bin/env python3
"""Generate platform wiring from one shared destination/exporter contract."""
from pathlib import Path
import argparse

ROOT = Path(__file__).resolve().parents[1]

def outputs():
    common = (ROOT / 'observability/components/exporters.alloy').read_text() + '\n' + (ROOT / 'observability/components/database.alloy').read_text()
    result = {}
    for platform, name in [('compose', 'config-compose.alloy'), ('kubernetes', 'config.alloy')]:
        text = '// Generated by scripts/sync_grot_alloy.py; edit observability/components instead.\n' + common + '\n' + (ROOT / f'observability/components/{platform}.alloy').read_text()
        if platform == 'compose': text += '\n' + (ROOT / 'observability/components/docker-infrastructure.alloy').read_text()
        result[ROOT / 'observability' / name] = text
        if platform == 'kubernetes': result[ROOT / 'deploy/telemetry-chart/files/config.alloy'] = text
    result[ROOT / 'deploy/telemetry-chart/files/default.conf.template'] = (ROOT / 'deploy/gateway/default.conf.template').read_text()
    for source, target in [('init.sql', 'postgres-init.sql'), ('postgresql.conf', 'postgresql.conf')]:
        result[ROOT / 'src/app/chart/files' / target] = (ROOT / 'deploy/postgres' / source).read_text()
    return result

if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    for path, text in outputs().items():
        if args.check:
            if not path.exists() or path.read_text() != text:
                raise SystemExit(f'Generated collector config is stale: {path.relative_to(ROOT)}')
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text)
